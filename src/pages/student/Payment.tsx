import { useState } from 'react';
import { Button, Card, Badge, PageHeader } from '../../components/ui';
import type { Payment, View } from '../../types';
import { courses } from '../../data';
import { paymentsAPI } from '../../services/api';
import { formatColomboDate, formatColomboDisplayDate, SRI_LANKA_TZ } from '../../utils/dateFormatter';

interface Props {
  navigate: (view: View) => void;
  onPaymentComplete: (payment: Payment) => void;
  enrolledCourseIds: string[];
}

const methods = [
  {
    id: 'card',
    label: 'Card',
    icon: '💳',
    desc: 'Visa / Mastercard / Amex',
  },
  {
    id: 'bank_transfer',
    label: 'Bank Transfer',
    icon: '🏦',
    desc: 'Upload your payment receipt',
  },
];

const methodMap: Record<string, Payment['method']> = {
  card: 'Card',
  bank_transfer: 'Bank Transfer',
};

export default function Payment({
  navigate,
  onPaymentComplete,
  enrolledCourseIds,
}: Props) {
  const [selectedCourse, setSelectedCourse] = useState(
    enrolledCourseIds[0] || ''
  );

  const [method, setMethod] = useState('card');
  const [loading, setLoading] = useState(false);
  const [success, setSuccess] = useState(false);
  const [payRef, setPayRef] = useState('');

  const [receipt, setReceipt] = useState('');
  const [receiptName, setReceiptName] = useState('');
  const [receiptFile, setReceiptFile] = useState<File | null>(null);
  const [paymentType, setPaymentType] = useState<'FULL' | 'INSTALLMENT'>('FULL');

  const enrolled = courses.filter((c) =>
    enrolledCourseIds.includes(c.id)
  );

  const course = enrolled.find((c) => c.id === selectedCourse);
  const installmentServiceFee = 1500;
  const installmentTotal = course ? course.monthlyFee + installmentServiceFee : 0;
  const monthlyInstallment = course ? Math.round(installmentTotal / 3) : 0;
  const selectedAmount = course
    ? paymentType === 'FULL'
      ? course.monthlyFee
      : monthlyInstallment
    : 0;

  // ============================================================
  // SUBMIT PAYMENT TO BACKEND
  // ============================================================

  const [cardExpiry, setCardExpiry] = useState('');

  const validateCardExpiry = (expiry: string): boolean => {
    if (!expiry || !expiry.includes('/')) return false;
    const parts = expiry.split('/');
    const month = parseInt(parts[0].trim(), 10);
    let year = parseInt(parts[1].trim(), 10);
    if (isNaN(month) || isNaN(year) || month < 1 || month > 12) return false;
    if (year < 100) year += 2000;
    const currentYear = new Date().getFullYear();
    const currentMonth = new Date().getMonth() + 1;
    if (year < currentYear) return false;
    if (year === currentYear && month < currentMonth) return false;
    return true;
  };

  const handlePay = async () => {
    if (!course) {
      alert('Please select a course.');
      return;
    }

    if (method === 'card') {
      if (!validateCardExpiry(cardExpiry)) {
        alert('Card has expired. Please enter a valid future expiry date (MM/YY).');
        return;
      }
    } else if (!receiptFile) {
      alert('Please upload your bank payment receipt.');
      return;
    }

    setLoading(true);

    try {
      /*
       * IMPORTANT:
       * We do NOT generate the payment reference here.
       * The backend will generate the real paymentReference.
       *
       * We also do NOT send card number / CVV to the backend.
       * This is a simulated payment record for your project.
       */

      const paymentData = new FormData();
      paymentData.append('purpose', 'COURSE_FEE');
      paymentData.append('relatedCourse', course.id);
      paymentData.append('paymentMethod', method === 'card' ? 'CARD' : 'BANK_TRANSFER');
      paymentData.append('transactionId', '');
      paymentData.append('paymentPlan', paymentType);
      paymentData.append('installmentNumber', '1');
      paymentData.append('totalInstallments', '3');
      paymentData.append('installmentServiceFee', String(installmentServiceFee));
      paymentData.append('notes', `${paymentType === 'INSTALLMENT' ? 'Installment 1 of 3' : 'Full payment'} course fee payment for ${course.name}`);
      if (receiptFile) {
        paymentData.append('receiptImage', receiptFile);
      }

      console.log('Submitting payment:', paymentData);

      // Send payment to MongoDB through backend
      const response = await paymentsAPI.create(paymentData);

      console.log('Payment saved successfully:', response);

      /*
       * Depending on your API response structure,
       * the actual payment may be inside response.data.
       */

      const backendPayment = response?.data || response;

      // Get the reference generated by the backend
      const paymentReference =
        backendPayment?.paymentReference ||
        backendPayment?.reference ||
        'PAYMENT-PENDING';

      // Convert backend payment to your frontend Payment type
      const payment: Payment = {
        id:
          backendPayment?._id ||
          backendPayment?.id ||
          paymentReference,

        reference: paymentReference,

        date: formatColomboDate(backendPayment?.paymentDate || new Date()),

        description: `${paymentType === 'INSTALLMENT' ? 'Installment 1 of 3' : 'Course Fee Payment'}: ${course.name} — ${new Intl.DateTimeFormat('en-US', {
          timeZone: SRI_LANKA_TZ,
          month: 'long',
          year: 'numeric',
        }).format(new Date())}`,

        amount: backendPayment?.amount || selectedAmount,

        method: methodMap[method],

        status: 'Pending',

        relatedTo:
          backendPayment?.relatedCourse?.title ||
          course.name,

        receipt: backendPayment?.paymentEvidence || undefined,
        paymentPlan: backendPayment?.paymentPlan || paymentType,
        installmentNumber: backendPayment?.installment?.installmentNumber || 1,
        totalInstallments: backendPayment?.installment?.totalInstallments || 3,
        totalPayable: backendPayment?.installment?.totalPayable || (paymentType === 'INSTALLMENT' ? installmentTotal : course.monthlyFee),
        paidAmount: backendPayment?.installment?.paidAmount || selectedAmount,
        remainingAmount: backendPayment?.installment?.remainingAmount || (paymentType === 'INSTALLMENT' ? installmentTotal - selectedAmount : 0),
        nextDueDate: backendPayment?.installment?.nextDueDate || '',
      };

      // Update parent/frontend state
      onPaymentComplete(payment);

      // Show backend-generated payment reference
      setPayRef(paymentReference);

      setLoading(false);
      setSuccess(true);
    } catch (error: any) {
      console.error('Payment submission failed:', error);

      setLoading(false);

      alert(
        error?.message ||
          'Payment could not be submitted. Please check your connection and try again.'
      );
    }
  };

  // ============================================================
  // SUCCESS SCREEN
  // ============================================================

  if (success) {
    return (
      <div className="flex items-center justify-center min-h-[70vh] fade-in-up">
        <Card className="max-w-md w-full p-10 text-center">
          <div className="w-20 h-20 rounded-full bg-green-100 flex items-center justify-center text-4xl mx-auto mb-6">
            ✅
          </div>

          <h2 className="text-2xl font-bold font-display text-slate-900 mb-2">
            Payment Submitted!
          </h2>

          <p className="text-slate-500 text-sm mb-6">
            Your payment has been submitted successfully. It will be
            reviewed by the institute.
          </p>

          <div className="bg-slate-50 rounded-xl p-4 space-y-2 text-sm text-left mb-6">
            <div className="flex justify-between">
              <span className="text-slate-400">
                Payment Reference
              </span>

              <span className="font-bold">
                {payRef}
              </span>
            </div>

            <div className="flex justify-between">
              <span className="text-slate-400">
                Course
              </span>

              <span className="font-medium">
                {course?.name}
              </span>
            </div>

            <div className="flex justify-between">
              <span className="text-slate-400">
                Amount
              </span>

              <span className="font-bold text-[#1E6BB8]">
                Rs. {selectedAmount.toLocaleString()}
              </span>
            </div>

            <div className="flex justify-between">
              <span className="text-slate-400">
                Method
              </span>

              <span className="font-medium">
                {methodMap[method]}
              </span>
            </div>

            <div className="flex justify-between items-center">
              <span className="text-slate-400">
                Status
              </span>

              <Badge color="amber">
                Pending Review
              </Badge>
            </div>
          </div>

          <div className="space-y-2">
            <Button
              fullWidth
              onClick={() =>
                navigate('student-payment-history')
              }
            >
              View Payment Records
            </Button>

            <Button
              fullWidth
              variant="outline"
              onClick={() =>
                navigate('student-dashboard')
              }
            >
              Back to Dashboard
            </Button>
          </div>
        </Card>
      </div>
    );
  }

  // ============================================================
  // PAYMENT PAGE
  // ============================================================

  return (
    <div className="fade-in-up space-y-6 max-w-2xl mx-auto">
      <PageHeader
        title="Initiate Payment"
        subtitle="Make a course fee payment"
      />

      <Card className="p-6 space-y-5">

        {/* =====================================================
            NO ENROLLMENT
        ====================================================== */}

        {enrolled.length === 0 ? (
          <div className="text-center py-8 text-slate-400">
            <p>You are not enrolled in any courses.</p>

            <Button
              className="mt-4"
              onClick={() =>
                navigate('student-courses')
              }
            >
              Browse Courses
            </Button>
          </div>
        ) : (
          <>
            {/* =================================================
                COURSE SELECTION
            ================================================== */}

            <div>
              <label className="text-sm font-medium text-slate-700 mb-2 block">
                Payment For
                <span className="text-red-500">*</span>
              </label>

              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                {enrolled.map((c) => (
                  <button
                    key={c.id}
                    onClick={() =>
                      setSelectedCourse(c.id)
                    }
                    className={`p-4 rounded-xl border-2 text-left transition-all ${
                      selectedCourse === c.id
                        ? 'border-[#1E6BB8] bg-blue-50'
                        : 'border-slate-200 hover:border-slate-300'
                    }`}
                  >
                    <p className="font-semibold text-sm text-slate-800">
                      {c.name}
                    </p>

                    <p className="text-xs text-slate-400">
                      Monthly: Rs.{' '}
                      {c.monthlyFee.toLocaleString()}
                    </p>

                    <p className="text-xs text-slate-400">
                      {c.teacher}
                    </p>
                  </button>
                ))}
              </div>
            </div>

            {course && (
              <>
                {/* =============================================
                    PAYMENT SUMMARY
                ============================================== */}

                <div className="bg-slate-50 rounded-xl p-4 space-y-2 text-sm">
                  <p className="font-semibold text-slate-700 mb-2">
                    Payment Summary
                  </p>

                  <div className="flex justify-between">
                    <span className="text-slate-400">
                      Reference
                    </span>

                    <span className="font-mono font-bold text-slate-800">
                      Generated after submission
                    </span>
                  </div>

                  <div className="flex justify-between gap-4">
                    <span className="text-slate-400">
                      Description
                    </span>

                    <span className="text-right">
                      {course.name} —{' '}
                      {new Intl.DateTimeFormat('en-US', {
                        timeZone: SRI_LANKA_TZ,
                        month: 'long',
                        year: 'numeric',
                      }).format(new Date())}
                    </span>
                  </div>

                  <div className="grid grid-cols-1 gap-2 sm:grid-cols-2">
                    <button
                      type="button"
                      onClick={() => setPaymentType('FULL')}
                      className={`rounded-xl border-2 p-3 text-left transition-all ${
                        paymentType === 'FULL'
                          ? 'border-[#1E6BB8] bg-blue-50'
                          : 'border-slate-200 hover:border-slate-300'
                      }`}
                    >
                      <p className="text-sm font-bold text-slate-800">Full Payment</p>
                      <p className="mt-1 text-lg font-black text-[#1E6BB8]">Rs. {course.monthlyFee.toLocaleString()}</p>
                    </button>
                    <button
                      type="button"
                      onClick={() => setPaymentType('INSTALLMENT')}
                      className={`rounded-xl border-2 p-3 text-left transition-all ${
                        paymentType === 'INSTALLMENT'
                          ? 'border-[#1E6BB8] bg-blue-50'
                          : 'border-slate-200 hover:border-slate-300'
                      }`}
                    >
                      <p className="text-sm font-bold text-slate-800">3-Month Installment</p>
                      <p className="mt-1 text-lg font-black text-[#1E6BB8]">Rs. {monthlyInstallment.toLocaleString()}</p>
                      <p className="mt-1 text-xs text-slate-500">Remaining Rs. {(installmentTotal - monthlyInstallment).toLocaleString()}</p>
                    </button>
                  </div>

                  <div className="flex justify-between">
                    <span className="text-slate-400">
                      Amount
                    </span>

                    <span className="font-bold text-xl text-[#1E6BB8]">
                      Rs.{' '}
                      {selectedAmount.toLocaleString()}
                    </span>
                  </div>

                  <div className="flex justify-between">
                    <span className="text-slate-400">
                      Date
                    </span>

                    <span>
                      {formatColomboDisplayDate(new Date())}
                    </span>
                  </div>
                </div>

                {/* =============================================
                    PAYMENT METHOD
                ============================================== */}

                <div>
                  <label className="text-sm font-medium text-slate-700 mb-3 block">
                    Payment Method
                    <span className="text-red-500">*</span>
                  </label>

                  <div className="grid grid-cols-2 gap-3">
                    {methods.map((m) => (
                      <button
                        key={m.id}
                        onClick={() =>
                          setMethod(m.id)
                        }
                        className={`p-3 rounded-xl border-2 text-left transition-all ${
                          method === m.id
                            ? 'border-[#1E6BB8] bg-blue-50'
                            : 'border-slate-200 hover:border-slate-300'
                        }`}
                      >
                        <div className="text-2xl mb-1">
                          {m.icon}
                        </div>

                        <p className="text-sm font-semibold text-slate-800">
                          {m.label}
                        </p>

                        <p className="text-xs text-slate-400">
                          {m.desc}
                        </p>
                      </button>
                    ))}
                  </div>
                </div>

                {/* =============================================
                    CARD DETAILS
                ============================================== */}

                {method === 'card' && (
                  <div className="space-y-3">

                    <div>
                      <label className="text-sm font-medium text-slate-700 mb-1 block">
                        Card Number
                      </label>

                      <input
                        placeholder="1234 5678 9012 3456"
                        maxLength={19}
                        inputMode="numeric"
                        className="w-full rounded-xl border border-slate-200 px-4 py-2.5 text-sm focus:outline-none focus:ring-2 focus:ring-[#1E6BB8]/40 focus:border-[#1E6BB8]"
                      />
                    </div>

                    <div className="grid grid-cols-2 gap-3">

                      <div>
                        <label className="text-sm font-medium text-slate-700 mb-1 block">
                          Expiry Date
                        </label>

                        <input
                          placeholder="MM / YY"
                          maxLength={7}
                          value={cardExpiry}
                          onChange={e => setCardExpiry(e.target.value)}
                          className="w-full rounded-xl border border-slate-200 px-4 py-2.5 text-sm focus:outline-none focus:ring-2 focus:ring-[#1E6BB8]/40 focus:border-[#1E6BB8]"
                        />
                      </div>

                      <div>
                        <label className="text-sm font-medium text-slate-700 mb-1 block">
                          CVV
                        </label>

                        <input
                          placeholder="123"
                          maxLength={4}
                          type="password"
                          inputMode="numeric"
                          className="w-full rounded-xl border border-slate-200 px-4 py-2.5 text-sm focus:outline-none focus:ring-2 focus:ring-[#1E6BB8]/40 focus:border-[#1E6BB8]"
                        />
                      </div>

                    </div>

                    <div>
                      <label className="text-sm font-medium text-slate-700 mb-1 block">
                        Cardholder Name
                      </label>

                      <input
                        placeholder="Ayesha Fernando"
                        className="w-full rounded-xl border border-slate-200 px-4 py-2.5 text-sm focus:outline-none focus:ring-2 focus:ring-[#1E6BB8]/40 focus:border-[#1E6BB8]"
                      />
                    </div>

                    <div className="flex gap-3 items-center pt-1">
                      <span className="text-xs text-slate-400">
                        Accepted:
                      </span>

                      {['VISA', 'MC', 'AMEX'].map(
                        (b) => (
                          <span
                            key={b}
                            className="px-2 py-0.5 border border-slate-200 rounded text-xs font-bold text-slate-500"
                          >
                            {b}
                          </span>
                        )
                      )}
                    </div>

                  </div>
                )}

                {/* =============================================
                    PAYMENT NOTE
                ============================================== */}

                {method === 'card' && <div className="bg-amber-50 border border-amber-200 rounded-xl p-3 text-xs text-amber-700">
                  ⚠️{' '}
                  <strong>Note:</strong> This is a
                  payment record submission. Your payment
                  will be verified by the institute. Sprint
                  1 does not include real payment gateway
                  integration.
                </div>}

                {/* =============================================
                    RECEIPT UPLOAD
                ============================================== */}

                {method === 'bank_transfer' && <>
                <div className="rounded-2xl border border-blue-100 bg-blue-50/70 p-4">
                  <div className="flex items-start justify-between gap-4">
                    <div>
                      <p className="text-xs font-extrabold uppercase tracking-[0.16em] text-[#1E6BB8]">Bank transfer account details</p>
                      <p className="mt-1 text-sm font-semibold text-slate-600">Transfer the payment amount before uploading the receipt.</p>
                    </div>
                    <span className="rounded-xl bg-white px-3 py-1 text-xs font-extrabold text-[#1E6BB8] shadow-sm">Demo</span>
                  </div>
                  <div className="mt-4 grid gap-3 sm:grid-cols-3">
                    <div className="rounded-xl bg-white p-3 shadow-sm">
                      <p className="text-[10px] font-extrabold uppercase tracking-wider text-slate-400">Bank</p>
                      <p className="mt-1 text-sm font-extrabold text-slate-900">BOC</p>
                    </div>
                    <div className="rounded-xl bg-white p-3 shadow-sm">
                      <p className="text-[10px] font-extrabold uppercase tracking-wider text-slate-400">Account Number</p>
                      <p className="mt-1 font-mono text-sm font-extrabold text-slate-900">767821626</p>
                    </div>
                    <div className="rounded-xl bg-white p-3 shadow-sm">
                      <p className="text-[10px] font-extrabold uppercase tracking-wider text-slate-400">Account Name</p>
                      <p className="mt-1 text-sm font-extrabold text-slate-900">Thaniya Kariyawasam</p>
                    </div>
                  </div>
                  <p className="mt-3 text-xs font-semibold text-slate-500">Use your student name or payment reference as the transfer remark.</p>
                </div>

                <label className="block border-2 border-dashed border-slate-200 rounded-xl p-5 text-center hover:border-[#1E6BB8] cursor-pointer transition-colors">

                  {receipt &&
                  receipt.startsWith('data:image/') ? (
                    <img
                      src={receipt}
                      alt="Payment receipt preview"
                      className="mx-auto max-h-40 rounded-lg mb-3"
                    />
                  ) : receipt ? (
                    <div className="text-3xl mb-2">
                      📄
                    </div>
                  ) : (
                    <div className="text-3xl mb-2">
                      🧾
                    </div>
                  )}

                  <span className="text-sm font-semibold text-[#1E6BB8]">
                    Upload payment receipt
                  </span>

                  <span className="block text-xs text-slate-400 mt-1">
                    PNG, JPG, WEBP, or PDF up to 5MB
                  </span>

                  {receiptName && (
                    <span className="block text-xs text-slate-500 mt-2 truncate">
                      {receiptName}
                    </span>
                  )}

                  <input
                    type="file"
                    accept="image/png,image/jpeg,image/webp,application/pdf"
                    className="sr-only"
                    onChange={(event) => {
                      const file =
                        event.target.files?.[0];

                      if (!file) return;
                      event.target.value = '';

                      if (
                        !['image/png', 'image/jpeg', 'image/webp', 'application/pdf'].includes(file.type)
                      ) {
                        alert(
                          'Please upload a PNG, JPG, WEBP, or PDF file.'
                        );
                        return;
                      }

                      if (
                        file.size >
                        5 * 1024 * 1024
                      ) {
                        alert(
                          'File size must be less than 5MB.'
                        );
                        return;
                      }

                      setReceiptFile(file);
                      setReceiptName(file.name);

                      if (file.type === 'application/pdf') {
                        setReceipt('pdf');
                        return;
                      }

                      const reader =
                        new FileReader();

                      reader.onload = () => {
                        setReceipt(
                          String(reader.result)
                        );
                      };

                      reader.readAsDataURL(file);
                    }}
                  />
                </label>
                </>}

                {/* =============================================
                    SUBMIT PAYMENT
                ============================================== */}

                <Button
                  fullWidth
                  size="lg"
                  onClick={handlePay}
                  disabled={loading}
                >
                  {loading
                    ? 'Processing...'
                    : `Proceed with Payment — Rs. ${selectedAmount.toLocaleString()}`}
                </Button>
              </>
            )}
          </>
        )}
      </Card>
    </div>
  );
}
